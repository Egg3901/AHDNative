// Execute the source politicalMetrics seeder against an offline DB boundary.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const revision = "96831835fb6b28983aa14fe66cb6eae9ecfde84c";
const source = process.argv[2];
if (!source) throw new Error("Usage: node scripts/political-board-reference.mjs <clean Game checkout at 96831835>");
if (execFileSync("git", ["-C", source, "rev-parse", "HEAD"], { encoding: "utf8" }).trim() !== revision) {
  throw new Error("Game checkout must match the immutable source revision.");
}
if (execFileSync("git", ["-C", source, "status", "--porcelain", "--untracked-files=no"], { encoding: "utf8" }).trim()) {
  throw new Error("Game checkout must have no tracked modifications.");
}
const temporary = mkdtempSync(resolve(tmpdir(), "ahd-political-board-"));
const output = resolve(temporary, "boards.json");
const sourceModule = (path) => pathToFileURL(resolve(source, path)).href;
const engine = fileURLToPath(new URL("../packages/engine/src/index.ts", import.meta.url));
const code = `
import { writeFileSync } from 'node:fs';
import { createWorld } from ${JSON.stringify(pathToFileURL(engine).href)};
import { seedPoliticalMetrics } from ${JSON.stringify(sourceModule("src/lib/admin/seed/seedPoliticalMetrics.ts"))};
import { foldCabinetResiduals } from ${JSON.stringify(sourceModule("src/lib/politicalMetrics/cabinetResidual.ts"))};
const result = { boards: {}, oracle: {} };
async function main() {
  for (const era of ['1953', '1979', '1991', '2019']) {
    const native = createWorld({ era, countryId: 'US', seed: 'source-political-board-ids', playerName: 'Probe' });
    const states = Object.values(native.regions).map(row => ({ _id: row.id, countryId: row.countryId }));
    const captured = {};
    const db = { collection(name) {
      if (name === 'states') return { find() { return { toArray: async () => states }; } };
      if (name === 'politicalMetrics') return { bulkWrite: async ops => {
        for (const op of ops) { const row = op.updateOne.update.$set; captured[row._id] = {countryId: row.countryId, values: row.values}; }
      } };
      throw new Error('Unexpected source collection ' + name);
    } };
    await seedPoliticalMetrics(db, false, () => {}, Number(era), era + '-default');
    result.boards[era] = captured;
  }
  const contribution = { 'economy.workerSecurity': 0.944 };
  const first = foldCabinetResiduals({}, contribution);
  const second = foldCabinetResiduals(first, contribution);
  const faded = foldCabinetResiduals(second, {});
  result.oracle = { contribution, first, second, faded };
  writeFileSync(${JSON.stringify(output)}, JSON.stringify(result));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
`;
let result;
try {
  const probe = resolve(temporary, "probe.ts");
  writeFileSync(probe, code);
  execFileSync(fileURLToPath(new URL("../node_modules/.bin/tsx", import.meta.url)),
    ["--tsconfig", resolve(source, "tsconfig.json"), probe], { stdio: "inherit" });
  result = JSON.parse(readFileSync(output, "utf8"));
} finally {
  rmSync(temporary, { recursive: true });
}
writeFileSync(new URL("../packages/engine/src/metrics/politicalBoardSeeds.ts", import.meta.url),
  `// Generated by scripts/political-board-reference.mjs.\n// Game ${revision}: actual seedPoliticalMetrics, existing Native regions only.\nexport const POLITICAL_BOARD_SEEDS: Readonly<Record<string, Readonly<Record<string, { countryId: string; values: Readonly<Record<string, number>> }>>>> = ${JSON.stringify(result.boards, null, 2)};\n`);
writeFileSync(new URL("../packages/engine/src/metrics/politicalBoardOracle.json", import.meta.url), JSON.stringify(result.oracle, null, 2) + "\n");
console.log(JSON.stringify({ oracle: result.oracle, london: result.boards['2019'].LON.values['economy.workerSecurity'], regions: Object.fromEntries(Object.entries(result.boards).map(([era, rows]) => [era, Object.keys(rows).length])) }));
