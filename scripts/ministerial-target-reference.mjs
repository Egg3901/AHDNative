// Execute the source seed loader in a clean checkout of the pinned Game.
// No Native formulas or source metrics are substituted in this generator.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const revision = "96831835fb6b28983aa14fe66cb6eae9ecfde84c";
const source = process.argv[2];
if (!source) throw new Error("Usage: node scripts/ministerial-target-reference.mjs <clean Game checkout at 96831835>");
if (execFileSync("git", ["-C", source, "rev-parse", "HEAD"], { encoding: "utf8" }).trim() !== revision) {
  throw new Error("The Game checkout must match the immutable source revision.");
}
if (execFileSync("git", ["-C", source, "status", "--porcelain", "--untracked-files=no"], { encoding: "utf8" }).trim()) {
  throw new Error("The Game checkout must have no tracked modifications.");
}
const loader = pathToFileURL(resolve(source, "src/lib/states/conditions/seedMetricsLoader.ts")).href;
const temporary = mkdtempSync(resolve(tmpdir(), "ahd-ministerial-target-"));
const result = resolve(temporary, "seeds.json");
const code = `
import { writeFileSync } from 'node:fs';
import { loadSeededStateMetrics } from ${JSON.stringify(loader)};
const seeds = {};
for (const country of ['UK', 'DE']) {
  for (const era of ['1953', '1979', '1991', '2019']) {
    seeds[country + ':' + era] = Object.fromEntries(
      loadSeededStateMetrics(country, era + '-default').map(row =>
        [String(row._id), row.economic.unemploymentRate.value]));
  }
}
writeFileSync(${JSON.stringify(result)}, JSON.stringify(seeds));
`;
const probe = resolve(temporary, "probe.ts");
let seeds;
try {
  writeFileSync(probe, code);
  execFileSync(fileURLToPath(new URL("../node_modules/.bin/tsx", import.meta.url)),
    ["--tsconfig", resolve(source, "tsconfig.json"), probe], { stdio: "inherit" });
  seeds = JSON.parse(readFileSync(result, "utf8"));
} finally {
  rmSync(temporary, { recursive: true });
}
const target = new URL("../packages/engine/src/metrics/ministerialTargetSeeds.ts", import.meta.url);
writeFileSync(target, `// Generated by scripts/ministerial-target-reference.mjs.\n// Game ${revision}: loadSeededStateMetrics, UK/DE unemployment targets.\nexport const MINISTERIAL_TARGET_SEEDS: Readonly<Record<string, Readonly<Record<string, number>>>> = ${JSON.stringify(seeds, null, 2)};\n`);
