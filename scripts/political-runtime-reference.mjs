// Reproduce the pure source political runtime, with reviewed input provenance.
import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const revision = "96831835fb6b28983aa14fe66cb6eae9ecfde84c";
const root = resolve(process.argv[2] ?? "");
if (!process.argv[2]) throw new Error("Pass a clean Game checkout at the recorded source revision.");
if (execFileSync("git", ["-C", root, "rev-parse", "HEAD"], {encoding:"utf8"}).trim() !== revision
  || execFileSync("git", ["-C", root, "status", "--porcelain", "--untracked-files=no"], {encoding:"utf8"}).trim()) {
  throw new Error("The source checkout must match the clean immutable revision.");
}
const entry = `
export { politicalNodeTargets } from './src/lib/politicalMetrics/engineNodes';
export { engineTermFor } from './src/lib/politicalMetrics/engineTerm';
export { macroResidualFor } from './src/lib/politicalLegislation/macroResidual';
export { legacyPoliticalHalfFromBoard } from './src/lib/politicalLegislation/legacyProjection';
export { lawTargets, structuralResidual, composeTarget, driftStep } from './src/lib/politicalLegislation/dynamics';
export { getCatalog } from './src/lib/politicalLegislation/catalog';
export { getNeutralFederalSalesTaxRate, getNeutralStateSalesTaxRate } from './src/lib/turn/gdpGrowth';
export { NATIONAL_SCOPE_IDS } from './src/lib/constants/nationalScope';
`;
const result = await build({stdin:{contents:entry,resolveDir:root,sourcefile:"source-political-runtime-entry.ts",loader:"ts"},
  absWorkingDir:root,bundle:true,format:"esm",target:"es2022",platform:"neutral",
  alias:{"@":root+"/src","@shared":root+"/shared"},write:false,metafile:true,legalComments:"none"});
const code = result.outputFiles[0].text.replace(/[\u2013\u2014]/g,"-");
if (/Math\.random|Date\.now|process\.env|fetch\(|\/root\//.test(code)) throw new Error("Runtime output is not pure or contains a local path.");
const output = new URL("../packages/engine/src/politicalMetrics/sourceRuntime.mjs", import.meta.url);
writeFileSync(output, `// Generated by scripts/political-runtime-reference.mjs.\n// Pure AHDGame ${revision} political runtime.\n`+code);
const inputs = Object.keys(result.metafile.inputs).filter(path=>path.startsWith("src/")).sort().map(path=>({
  path, sha256:createHash("sha256").update(readFileSync(resolve(root,path))).digest("hex"),
}));
writeFileSync(new URL("../packages/engine/src/politicalMetrics/sourceRuntime.provenance.json",import.meta.url),JSON.stringify({
  repository:"https://github.com/Egg3901/AHDGame",revision,generator:"scripts/political-runtime-reference.mjs",
  inputs,outputSha256:createHash("sha256").update(readFileSync(fileURLToPath(output))).digest("hex"),
},null,2)+"\n");
console.log(JSON.stringify({sourceModules:inputs.length,bytes:code.length}));
